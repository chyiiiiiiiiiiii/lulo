import 'dart:io';

import 'package:agent_core/agent_core.dart';

/// Writes the native copy of the turn-taking lexicon, or checks it is current.
///
/// The endpointer that runs is native — it is consulted on a 50ms tick inside
/// the audio path, and `pigeons/voice_host_api.dart` records why a hop across
/// the platform channel per tick is not worth what the decision saves. A
/// second platform's endpointer will sit in its own audio loop for the same
/// reason, so the matcher is written once per platform.
///
/// The words are not. `TurnCompletion` in `agent_core` holds the only copy,
/// and this writes it out for Swift the way `flutter pub get` writes the l10n
/// and `build_runner` writes the drift queries: generated, committed, and
/// diffed by the gate. A list edited on one side and not the other then fails
/// `verify.dart` rather than the conversation.
///
/// ```sh
/// dart run tool/generate_turn_taking_lexicon.dart          # write
/// dart run tool/generate_turn_taking_lexicon.dart --check  # gate
/// ```
Future<void> main(List<String> arguments) async {
  final bool checking = arguments.contains('--check');
  final File destination = File(
    'apps/local_agent_macos/macos/Runner/GeneratedTurnTakingLexicon.swift',
  );
  final String generated = _swiftSource();

  if (!checking) {
    destination.writeAsStringSync(generated);
    stdout.writeln('Wrote ${destination.path}');
    return;
  }

  if (!destination.existsSync()) {
    stderr.writeln(
      '${destination.path} is missing. Run '
      '`dart run tool/generate_turn_taking_lexicon.dart`.',
    );
    exitCode = 1;
    return;
  }
  if (destination.readAsStringSync() != generated) {
    stderr.writeln(
      '${destination.path} disagrees with the lexicon in agent_core. '
      'Run `dart run tool/generate_turn_taking_lexicon.dart` and commit the '
      'result — the words are edited in '
      'packages/agent_core/lib/src/voice/turn_completion.dart, never here.',
    );
    exitCode = 1;
    return;
  }
  stdout.writeln('${destination.path} is current.');
}

/// The whole Swift file, as text.
String _swiftSource() {
  final StringBuffer out = StringBuffer()
    ..writeln('// Generated by tool/generate_turn_taking_lexicon.dart.')
    ..writeln('// Do not edit: the words live in agent_core, in')
    ..writeln('// packages/agent_core/lib/src/voice/turn_completion.dart, and')
    ..writeln('// `verify.dart` regenerates this file and fails on a diff.')
    ..writeln('//')
    ..writeln('// The matcher that reads these is native on purpose. The')
    ..writeln('// endpointer runs on a 50ms tick in the audio path, so the')
    ..writeln('// decision stays next to the audio and only the lexicon')
    ..writeln('// crosses the language boundary — at build time, not at run')
    ..writeln('// time.')
    ..writeln()
    ..writeln('import Foundation')
    ..writeln()
    ..writeln('/// The words and thresholds `TurnCompletion` decides with.')
    ..writeln('enum TurnTakingLexicon {')
    ..writeln('  /// How much longer a half-finished thought is given.')
    ..writeln(
      '  static let continuingGrace: TimeInterval = '
      '${_seconds(TurnCompletion.continuingGrace)}',
    )
    ..writeln()
    ..writeln('  /// How much sooner a visibly finished question is submitted.')
    ..writeln(
      '  static let settledSaving: TimeInterval = '
      '${_seconds(TurnCompletion.settledSaving)}',
    )
    ..writeln()
    ..writeln('  /// How much has to have been said before "finished" is')
    ..writeln('  /// believable.')
    ..writeln(
      '  static let syllablesToBeFinished = '
      '${TurnCompletion.syllablesToBeFinished}',
    )
    ..writeln()
    ..writeln('  /// Endings that introduce more words after a pause.')
    ..write(
      _list(
        'continuingSuffixes',
        '[String]',
        TurnCompletion.continuingSuffixes,
      ),
    )
    ..writeln()
    ..writeln('  /// The same, in Latin script, matched as a whole final word.')
    ..write(
      _list(
        'continuingWords',
        'Set<String>',
        TurnCompletion.continuingWords.toList(),
      ),
    )
    ..writeln()
    ..writeln('  /// Endings that mean the question has been asked.')
    ..write(
      _list('settledSuffixes', '[String]', TurnCompletion.settledSuffixes),
    )
    ..writeln()
    ..writeln('  /// What the recogniser writes when a sentence ended.')
    ..write(
      _characters(
        'terminalPunctuation',
        TurnCompletion.terminalPunctuation.toList(),
      ),
    )
    ..writeln('}');
  return out.toString();
}

/// A `Duration` as the Swift literal for its value in seconds.
String _seconds(Duration duration) {
  final double value = duration.inMicroseconds / Duration.microsecondsPerSecond;
  final String written = value.toString();
  // `1.0` reads as an accident beside `0.6`; a whole number of seconds is
  // written as one.
  return written.endsWith('.0')
      ? written.substring(0, written.length - 2)
      : written;
}

/// One `static let` holding a collection of strings, wrapped one per line.
String _list(String name, String type, List<String> entries) {
  final StringBuffer out = StringBuffer('  static let $name: $type = [\n');
  for (final String entry in entries) {
    out.writeln('    ${_quoted(entry)},');
  }
  return (out..writeln('  ]')).toString();
}

/// The same, as `Character` literals rather than strings.
String _characters(String name, List<String> entries) {
  final StringBuffer out = StringBuffer(
    '  static let $name: Set<Character> = [\n',
  );
  for (final String entry in entries) {
    out.writeln('    ${_quoted(entry)},');
  }
  return (out..writeln('  ]')).toString();
}

/// [value] as a Swift string literal.
///
/// Escaped rather than interpolated raw: nothing in the lexicon carries a
/// quote or a backslash today, and a word added later that does must not
/// silently produce a file that no longer compiles.
String _quoted(String value) {
  final String escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll('"', r'\"')
      .replaceAll('\n', r'\n')
      .replaceAll('\t', r'\t');
  return '"$escaped"';
}
